const domainFor = (auditId) => {
  const [family, numberText] = auditId.split("-");
  const number = Number(numberText);
  if (family === "ORD") return "order_management";
  if (family === "SHP") return "shipment_logistics";
  if (family === "QC") return "quality_control";
  if (family === "ITM") return number <= 5 ? "catalog_master_data" : "product_information";
  if (family === "VEN") return "catalog_master_data";
  if (family === "SAM") return "samples";
  if (family === "WF") return "workflow";
  if (family === "CMP") return "complaints";
  if (auditId === "OTH-01" || auditId === "OTH-02") return "communication";
  if (auditId === "OTH-03") return "reporting_exports";
  if (auditId === "OTH-04") return "platform_operations";
  return "access_security";
};

const statusFor = (entry) => {
  if (["NOT_ASSISTANT_SAFE", "EXPORT_ONLY", "PRESENTATION_ONLY"].includes(entry.assistantRecommendation)) {
    return "not_tool_eligible";
  }
  if (entry.id === "product_analytics") return "blocked_business_confirmation";
  if (EXISTING_ASSISTANT_FEATURES.has(entry.id)) return "existing_assistant_feature";
  return entry.assistantStatus || "not_ready";
};

const capability = (entry) => {
  const canonicalFile = entry.canonicalFile;
  const canonicalSymbols = entry.canonicalSymbols || [];
  const controllerLocal = entry.controllerLocal ?? canonicalFile.includes("/controllers/");
  const sourceKind = entry.sourceKind || (controllerLocal ? "canonical_report_query" : "collection");
  const sourceIsCanonical = !["DUPLICATED_LOGIC", "PRESENTATION_ONLY", "UNCLEAR"].includes(entry.sourceClass);
  const recommendation = entry.assistantRecommendation;
  const sensitive = recommendation === "NOT_ASSISTANT_SAFE";
  const rawMongoMode = recommendation === "RAW_MONGO"
    ? "preferred_scoped_projection"
    : recommendation === "CAPABILITY_PLUS_MONGO"
      ? "supplemental_scoped_projection"
      : sensitive ? "denied" : "not_primary";
  const entryFilters = entry.filters || [];
  const outputFields = entry.outputFields || [];
  return {
    id: entry.id,
    auditId: entry.auditId,
    name: entry.name,
    domain: entry.domain || domainFor(entry.auditId),
    description: entry.description,
    businessPurpose: entry.businessPurpose,
    type: entry.type,
    sourceClass: entry.sourceClass,
    assistantRecommendation: recommendation,
    assistantStatus: statusFor(entry),
    keywords: entry.keywords || [],
    aliases: entry.aliases || [],
    userIntentExamples: entry.userIntentExamples || [],
    collections: entry.collections || [],
    relationships: entry.relationships || [],
    routes: entry.routes || [],
    sourceOfTruth: {
      kind: sourceKind,
      canonical: sourceIsCanonical,
      canonicalFile,
      canonicalSymbols,
      reusable: entry.reusable ?? recommendation === "DIRECT_CAPABILITY",
      controllerLocal,
      fallbackRules: entry.fallbackRules || [],
      rawFactsWarning: entry.rawFactsWarning || "",
    },
    filters: entryFilters,
    outputFields,
    inputs: entryFilters.map((item) => item.name),
    outputs: outputFields.map((item) => item.name),
    dateSemantics: entry.dateSemantics || dateSemantics(),
    quantitySemantics: entry.quantitySemantics || [],
    cbmSemantics: entry.cbmSemantics || noCbm(),
    statusSemantics: entry.statusSemantics || noStatus(),
    resultGrain: entry.resultGrain,
    sourceProvenance: {
      audit: AUDIT_SOURCE,
      implementation: canonicalSymbols.length ? `${canonicalFile}#${canonicalSymbols.join(",")}` : canonicalFile,
      behavior: "current executable behavior as audited on 2026-08-20",
    },
    rawMongoPolicy: {
      mode: rawMongoMode,
      notes: entry.rawMongoNotes || (sensitive
        ? "Generic Assistant Mongo access remains denied."
        : "Existing read-only collection deny rules remain authoritative."),
    },
    safety: {
      readOnly: true,
      sensitive,
      mutationAllowed: false,
      approvedProjectionRequired: sensitive || entry.approvedProjectionRequired === true,
    },
    limitations: entry.limitations || [],
    uncertainties: entry.uncertainties || [],
    risks: entry.risks || [],
    sources: [
      { path: canonicalFile, symbols: canonicalSymbols },
      { path: AUDIT_SOURCE, symbols: [entry.auditId] },
    ],
    certainty: entry.certainty || (entry.sourceClass === "UNCLEAR" ? "unknown" : "verified"),
  };
};

