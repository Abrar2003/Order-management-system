const filter = (name, aliases = [], type = "string", required = false, semantics = "") => ({
  name, aliases, type, required, semantics,
});
const filters = (...names) => names.map((entry) => {
  if (typeof entry !== "string") return entry;
  const definition = FILTER_DEFINITIONS[entry];
  if (!definition) throw new Error(`Unknown Knowledge Base filter definition: ${entry}`);
  return filter(...definition);
});
const outputField = (name) => {
  const [meaning, valueType, provenance] = OUTPUT_DEFINITIONS[name]
    || [name.replaceAll("_", " "), "mixed", "audited current implementation"];
  return { name, meaning, valueType, provenance };
};
