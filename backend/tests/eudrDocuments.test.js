const test = require("node:test");
const assert = require("node:assert/strict");
const http = require("node:http");
const express = require("express");
const User = require("../models/user.model");
const EudrChain = require("../models/eudrChain.model");
const Party = require("../models/eudrParty.model");
const Vendor = require("../models/vendor.model");
const storage = require("../services/wasabiStorage.service");
const router = require("../routers/eudrChain.routes");
const { signAccessToken } = require("../services/authToken.service");

test("document previews and downloads enforce roles and chain ownership without altering review records", async (t) => {
  const previousSecret = process.env.JWT_SECRET;
  process.env.JWT_SECRET = "eudr-document-test-secret";
  t.after(() => { if (previousSecret === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = previousSecret; });
  const manager = { _id: "aaaaaaaaaaaaaaaaaaaaaaaa", role: "manager", name: "Reviewer" };
  const viewer = { _id: "bbbbbbbbbbbbbbbbbbbbbbbb", role: "viewer", name: "Viewer" };
  t.mock.method(User, "findById", (id) => ({ select: () => ({ populate: () => ({ lean: async () => String(id) === manager._id ? manager : viewer }) }) }));
  const chain = new EudrChain({ container: "C1", container_key: "c1", vendor: manager._id, declared_milli_cft: 1000, stages: [{ kind: "sawmill", verified_at: new Date(), documents: [{ type: "license", key: "private/license", name: "license.pdf", content_type: "application/pdf" }] }], history: [{ event: "stage_verified", actor_name: "Reviewer" }] });
  t.mock.method(EudrChain, "findById", async (id) => String(id) === String(chain._id) ? chain : null);
  const before = JSON.stringify(chain.toObject());
  const bytes = Buffer.from("%PDF-1.7 private test document");
  const ranges = [];
  let missing = false;
  const source = http.createServer((req, res) => {
    if (missing) { res.writeHead(404); return res.end(); }
    ranges.push(req.headers.range || "");
    res.setHeader("Accept-Ranges", "bytes");
    if (req.headers.range) { res.writeHead(206, { "Content-Length": 4, "Content-Range": `bytes 0-3/${bytes.length}` }); return res.end(bytes.subarray(0, 4)); }
    res.writeHead(200, { "Content-Length": bytes.length }); res.end(bytes);
  });
  await new Promise((resolve) => source.listen(0, "127.0.0.1", resolve));
  const calls = [];
  t.mock.method(storage, "getSignedObjectUrl", async (key, options) => { calls.push({ key, options }); return `http://127.0.0.1:${source.address().port}/file`; });
  const app = express(); app.use("/eudr", router);
  const server = app.listen(0, "127.0.0.1");
  await new Promise((resolve) => server.once("listening", resolve));
  t.after(() => { server.closeAllConnections(); source.closeAllConnections(); server.close(); source.close(); });
  const base = `http://127.0.0.1:${server.address().port}/eudr/${chain._id}/stages/${chain.stages[0]._id}/documents/${chain.stages[0].documents[0]._id}`;
  const headers = { Authorization: `Bearer ${signAccessToken(manager)}` };
  assert.equal((await fetch(`${base}/content`)).status, 401);
  assert.equal((await fetch(`${base}/preview`)).status, 401);
  assert.equal((await fetch(`${base}/preview`, { headers: { Authorization: `Bearer ${signAccessToken(viewer)}` } })).status, 403);
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/eudr/${chain._id}/contribution`, { method: "PATCH", headers: { Authorization: `Bearer ${signAccessToken(viewer)}` } })).status, 403);
  assert.equal((await fetch(`${base}/content`, { headers: { Authorization: `Bearer ${signAccessToken(viewer)}` } })).status, 403);
  assert.equal(calls.length, 0);
  const invalid = base.replace(String(chain.stages[0]._id), "cccccccccccccccccccccccc");
  assert.equal((await fetch(`${invalid}/content`, { headers })).status, 404);
  assert.equal((await fetch(`${invalid}/preview`, { headers })).status, 404);
  assert.equal((await fetch(`${invalid}/url`, { headers })).status, 404);
  assert.equal((await fetch(`${base.replace(String(chain._id), "dddddddddddddddddddddddd")}/content`, { headers })).status, 404);
  assert.equal(calls.length, 0);

  const preview = await fetch(`${base}/content`, { headers });
  assert.equal(preview.status, 200);
  assert.equal(preview.headers.get("cache-control"), "private, no-store");
  assert.match(preview.headers.get("access-control-expose-headers"), /Accept-Ranges/);
  assert.equal(preview.headers.get("content-type"), "application/pdf");
  assert.deepEqual(Buffer.from(await preview.arrayBuffer()), bytes);
  const partial = await fetch(`${base}/content`, { headers: { ...headers, Range: "bytes=0-3" } });
  assert.equal(partial.status, 206);
  assert.equal(partial.headers.get("content-range"), `bytes 0-3/${bytes.length}`);
  assert.equal(await partial.text(), "%PDF");
  assert.deepEqual(ranges, ["", "bytes=0-3"]);
  const download = await fetch(`${base}/url?download=1`, { headers });
  assert.equal(download.status, 200);
  assert.equal(calls.at(-1).options.download, true);
  assert.equal(calls.at(-1).options.expiresIn, 300);
  assert.equal(calls.at(-1).key, "private/license");
  missing = true;
  assert.equal((await fetch(`${base}/content`, { headers })).status, 404);
  assert.equal(JSON.stringify(chain.toObject()), before);
  chain.stages[0].documents[0].name = "invoice.docx";
  chain.stages[0].documents[0].content_type = "application/octet-stream";
  const beforeOffice = JSON.stringify(chain.toObject());
  const office = require("../services/eudrPreview.service");
  t.mock.method(office, "officePreview", async () => bytes);
  const converted = await fetch(`${base}/preview`, { headers });
  assert.equal(converted.status, 200); assert.equal(converted.headers.get("cache-control"), "private, no-store");
  assert.equal(converted.headers.get("content-type"), "application/pdf");
  assert.deepEqual(Buffer.from(await converted.arrayBuffer()), bytes);
  assert.equal(JSON.stringify(chain.toObject()), beforeOffice);
  t.mock.method(office, "officePreview", async () => { throw Object.assign(new Error("Conversion unavailable. Retry."), { statusCode: 503 }); });
  const failure = await fetch(`${base}/preview`, { headers });
  assert.equal(failure.status, 503); assert.match((await failure.json()).message, /Retry/);
  const directoryUrl = `http://127.0.0.1:${server.address().port}/eudr/directory?kind=sawmill`;
  assert.equal((await fetch(directoryUrl)).status, 401);
  const saved = { _id: "eeeeeeeeeeeeeeeeeeeeeeee", kind: "sawmill", name: "Mill [1]", fields: { gst: "GST-M", pan: "PAN-M" }, evidence: [{ _id: "ffffffffffffffffffffffff", key: "private/saved-license", name: "license.pdf", type: "license" }] };
  let search;
  t.mock.method(Party, "find", (query) => { search = query.name; return { sort: () => ({ limit: () => ({ lean: async () => [saved] }) }) }; });
  t.mock.method(Party, "findById", () => ({ lean: async () => saved }));
  const result = await fetch(`${directoryUrl}&search=Mill%20%5B1%5D`, { headers });
  assert.equal(result.status, 200); const entry = (await result.json()).data[0];
  assert.equal(entry.fields.gst, "GST-M"); assert.equal(entry.evidence[0].key, undefined);
  assert.ok(search.test("Mill [1]")); assert.ok(!search.test("Mill 1"));
  const detail = await fetch(`${directoryUrl.split("?")[0]}/${saved._id}`, { headers });
  assert.equal(detail.status, 200); assert.equal((await detail.json()).data.evidence[0].key, undefined);
  assert.equal((await fetch(directoryUrl, { headers: { Authorization: `Bearer ${signAccessToken(viewer)}` } })).status, 403);
  const vendorUrl = directoryUrl.replace("kind=sawmill", "kind=vendor");
  assert.equal((await fetch(vendorUrl)).status, 401);
  assert.equal((await fetch(vendorUrl, { headers: { Authorization: `Bearer ${signAccessToken(viewer)}` } })).status, 403);
  t.mock.method(Vendor, "find", (query) => {
    assert.equal(query.deleted_at, null); assert.deepEqual(query.is_active, { $ne: false });
    return { select: (fields) => { assert.equal(fields, "name gst pan"); return { sort: () => ({ limit: () => ({ lean: async () => [{ _id: saved._id, name: "Vendor", gst: "GST-V", pan: "PAN-V", email: "not-exposed" }] }) }) }; } };
  });
  const vendors = await fetch(vendorUrl, { headers }); assert.equal(vendors.status, 200);
  const buyer = (await vendors.json()).data[0]; assert.deepEqual(buyer.fields, { sold_to: "Vendor", buyer_gst: "GST-V", buyer_pan: "PAN-V" }); assert.equal(buyer.email, undefined);
});
